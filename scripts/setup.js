async function main() {
  console.log('🔌 Connecting to Supabase PostgreSQL...');
  await client.connect();
  console.log('✅ Connected\n');

  console.log('📐 Creating schema...');
  await client.query(SCHEMA_SQL);
  console.log('✅ Schema created\n');

  console.log('🌱 Seeding industries...');
  for (const ind of SEED) {
    await client.query(
      `INSERT INTO public.industries (id, name, slug, icon) VALUES ($1, $2, $3, $4)
       ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, icon = EXCLUDED.icon`,
      [ind.id, ind.name, ind.slug, ind.icon]
    );
    process.stdout.write(`  ✓ ${ind.name}\n`);
  }

  console.log('\n📋 Seeding system surveys and questions...');
  for (const ind of SEED) {
    for (let si = 0; si < ind.surveys.length; si++) {
      const sv = ind.surveys[si];

      // Insert survey
      const { rows } = await client.query(
        `INSERT INTO public.surveys (industry_id, title, is_system, user_id)
         VALUES ($1, $2, true, NULL)
         ON CONFLICT DO NOTHING
         RETURNING id`,
        [ind.id, sv.title]
      );

      // Get or find survey id
      let surveyId;
      if (rows.length > 0) {
        surveyId = rows[0].id;
      } else {
        const found = await client.query(
          `SELECT id FROM public.surveys WHERE industry_id = $1 AND title = $2 LIMIT 1`,
          [ind.id, sv.title]
        );
        surveyId = found.rows[0]?.id;
      }

      if (!surveyId) { console.log(`  ⚠ Could not get id for "${sv.title}"`); continue; }

      // Insert questions
      for (let qi = 0; qi < sv.questions.length; qi++) {
        await client.query(
          `INSERT INTO public.questions (survey_id, order_num, text)
           VALUES ($1, $2, $3)
           ON CONFLICT (survey_id, order_num) DO UPDATE SET text = EXCLUDED.text`,
          [surveyId, qi + 1, sv.questions[qi]]
        );
      }
      console.log(`  ✓ [${ind.name}] Опрос ${si + 1}: "${sv.title}" (${sv.questions.length} вопросов)`);
    }
  }

  console.log('\n✅ Database setup complete!');
  console.log(`   Industries: ${SEED.length}`);
  console.log(`   Surveys:    ${SEED.reduce((a, i) => a + i.surveys.length, 0)}`);
  console.log(`   Questions:  ${SEED.reduce((a, i) => a + i.surveys.reduce((b, s) => b + s.questions.length, 0), 0)}`);

  await client.end();
}

main().catch(err => { console.error('❌ Error:', err.message); process.exit(1); });
